#!/usr/bin/env node
// Generates migrations/0002_seed.sql from data/seed/settimane.json and data/seed/traguardi.json.
// Usage: npm run seed:generate
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));

const weeks = read('data/seed/settimane.json');
const { milestones } = read('data/seed/traguardi.json');

/** SQL string literal with single quotes escaped. */
const q = (value) => (value === null || value === undefined ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`);

if (weeks.weeks.length !== 104) throw new Error(`Expected 104 weeks, found ${weeks.weeks.length}`);

const lines = [
  '-- Generated by scripts/generate-seed.mjs. Do not edit by hand: edit data/seed/*.json and regenerate.',
  '',
  'INSERT INTO settings (key, value) VALUES',
  `  ('start_date', ${q(weeks.start_date)}),`,
  `  ('weekly_target_hours', ${q(String(weeks.weekly_target_hours))}),`,
  `  ('public_show_hours', 'false');`,
  '',
  'INSERT INTO weeks (n, phase_id, goal) VALUES',
  weeks.weeks.map((w) => `  (${Number(w.n)}, ${q(w.phase_id)}, ${q(w.goal)})`).join(',\n') + ';',
  '',
  'INSERT INTO milestones (id, title_it, title_en, due_date, phase_id, is_public, sort_order) VALUES',
  milestones
    .map(
      (m) =>
        `  (${q(m.id)}, ${q(m.title_it)}, ${q(m.title_en)}, ${q(m.due_date)}, ${q(m.phase_id)}, ${m.is_public ? 1 : 0}, ${Number(m.sort_order)})`,
    )
    .join(',\n') + ';',
  '',
];

const out = fileURLToPath(new URL('migrations/0002_seed.sql', root));
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out}: ${weeks.weeks.length} weeks, ${milestones.length} milestones.`);
