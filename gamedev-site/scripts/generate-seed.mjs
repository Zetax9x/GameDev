#!/usr/bin/env node
/**
 * Generates a migration that syncs the plan in D1 with data/seed/*.json:
 * week phases and goals, milestones and monthly checks.
 *
 * Usage: npm run seed:generate -- 0005_plan_update
 *
 * It is idempotent and keeps Yuri's data: sessions, journal, week status/notes/links,
 * milestone status/dates/notes and check progress are never touched.
 * Note: week goals edited from the dashboard are overwritten by the JSON goals.
 * (0002_seed.sql was the first seed and is kept as applied history.)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const name = process.argv[2];
if (!name || !/^\d{4}_[a-z0-9_]+$/.test(name)) {
  console.error('Usage: npm run seed:generate -- 0005_plan_update');
  process.exit(1);
}

const root = new URL('../', import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));
const weeks = read('data/seed/settimane.json');
const { milestones } = read('data/seed/traguardi.json');
const { months } = read('data/seed/verifiche.json');

/** SQL string literal with single quotes escaped. */
const q = (value) => (value === null || value === undefined ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`);

if (weeks.weeks.length !== 104) throw new Error(`Expected 104 weeks, found ${weeks.weeks.length}`);

const checkRows = months.flatMap((m) => m.items.map((item, i) => ({ ...item, month: m.month, sort: m.month * 100 + i })));
const inList = (ids) => ids.map(q).join(', ');

const lines = [
  `-- Generated by scripts/generate-seed.mjs (${name}). Edit data/seed/*.json and regenerate, do not edit by hand.`,
  '',
  "INSERT OR IGNORE INTO settings (key, value) VALUES ('start_date', " + q(weeks.start_date) + ");",
  "INSERT OR IGNORE INTO settings (key, value) VALUES ('public_show_hours', 'false');",
  "INSERT OR IGNORE INTO settings (key, value) VALUES ('weekly_target_hours', " + q(String(weeks.weekly_target_hours)) + ');',
  '',
  '-- Weeks: phase and goal from the plan; status, notes and links are kept.',
  'INSERT INTO weeks (n, phase_id, goal) VALUES',
  weeks.weeks.map((w) => `  (${Number(w.n)}, ${q(w.phase_id)}, ${q(w.goal)})`).join(',\n'),
  "ON CONFLICT(n) DO UPDATE SET phase_id = excluded.phase_id, goal = excluded.goal, updated_at = datetime('now');",
  '',
  '-- Milestones: titles, dates, phase, order and visibility from the plan; status, reached date and notes are kept.',
  'INSERT INTO milestones (id, title_it, title_en, due_date, phase_id, is_public, sort_order) VALUES',
  milestones
    .map(
      (m) =>
        `  (${q(m.id)}, ${q(m.title_it)}, ${q(m.title_en)}, ${q(m.due_date)}, ${q(m.phase_id)}, ${m.is_public ? 1 : 0}, ${Number(m.sort_order)})`,
    )
    .join(',\n'),
  'ON CONFLICT(id) DO UPDATE SET title_it = excluded.title_it, title_en = excluded.title_en, due_date = excluded.due_date,',
  '  phase_id = excluded.phase_id, is_public = excluded.is_public, sort_order = excluded.sort_order;',
  `DELETE FROM milestones WHERE id NOT IN (${inList(milestones.map((m) => m.id))});`,
  '',
  '-- Monthly checks: text and order from the plan; progress is kept.',
  'INSERT INTO checks (id, month, text, sort_order) VALUES',
  checkRows.map((c) => `  (${q(c.id)}, ${c.month}, ${q(c.text)}, ${c.sort})`).join(',\n'),
  'ON CONFLICT(id) DO UPDATE SET month = excluded.month, text = excluded.text, sort_order = excluded.sort_order;',
  `DELETE FROM checks WHERE id NOT IN (${inList(checkRows.map((c) => c.id))});`,
  '',
];

const out = fileURLToPath(new URL(`migrations/${name}.sql`, root));
if (existsSync(out)) {
  console.error(`${out} already exists: choose a new migration name.`);
  process.exit(1);
}
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out}: ${weeks.weeks.length} weeks, ${milestones.length} milestones, ${checkRows.length} checks.`);
